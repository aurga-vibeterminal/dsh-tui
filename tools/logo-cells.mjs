/**
 * Dev tool: rasterize the web app's whale favicon into half-block cell art
 * for the TUI startup banner.
 *
 * Pipeline: apps/web/public/favicon.svg --resvg--> RGBA pixels --sample-->
 * 28x28 grid --half-blocks--> src/logo-cells.ts (block-char rows + brand
 * color). Each terminal row carries two pixel rows: `▀` top half, `▄` bottom
 * half, `█` both, space neither — all drawn with the foreground color only,
 * so one truecolor run per contiguous run of blocks.
 *
 * Usage: node tools/logo-cells.mjs <path/to/favicon.svg>
 * Regenerate whenever the upstream logo changes; the output is committed.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { Resvg } from '@resvg/resvg-js'

const BRAND_RGB = [0x4d, 0x6b, 0xfe] // DeepSeek blue

const svgPath = process.argv[2]
if (svgPath === undefined) {
  console.error('usage: node tools/logo-cells.mjs <favicon.svg>')
  process.exit(1)
}

const svg = readFileSync(svgPath, 'utf8')
const resvg = new Resvg(svg, { fitTo: { mode: 'width', value: 200 } })
const png = resvg.render()
const { width, height, pixels } = { width: png.width, height: png.height, pixels: png.pixels }

/** Alpha coverage (0..1) at one rendered pixel. */
function pixelAlpha(x, y) {
  return pixels[(y * width + x) * 4 + 3] / 255
}

// Crop to the content bounding box so transparent margins don't pad the art.
let minX = width, minY = height, maxX = 0, maxY = 0
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    if (pixelAlpha(x, y) > 0.1) {
      if (x < minX) minX = x
      if (x > maxX) maxX = x
      if (y < minY) minY = y
      if (y > maxY) maxY = y
    }
  }
}
const boxWidth = maxX - minX + 1
const boxHeight = maxY - minY + 1

// 16 columns wide — the practical floor where the whale silhouette still
// reads (below this the spout and tail blur together). The pixel height
// follows the content aspect, and the half-block grid is half that (each
// terminal row carries two pixel rows).
const COLUMNS = 16
const pixelRows = Math.max(12, Math.round((boxHeight / boxWidth) * COLUMNS))
const ROWS = Math.ceil(pixelRows / 2)

/** Alpha coverage of one box-relative source point (0..1). */
function alphaAt(x, y) {
  const px = Math.min(width - 1, minX + Math.floor((x / COLUMNS) * boxWidth))
  const py = Math.min(height - 1, minY + Math.floor((y / pixelRows) * boxHeight))
  return pixelAlpha(px, py)
}

/** Coverage of one grid cell, averaged over its source-pixel area. */
function coverage(cx, cy) {
  let sum = 0
  const samples = 3
  for (let sy = 0; sy < samples; sy++) {
    for (let sx = 0; sx < samples; sx++) {
      const x = cx + (sx + 0.5) / samples
      const y = cy + (sy + 0.5) / samples
      sum += alphaAt(x, y)
    }
  }
  return sum / (samples * samples)
}

const rows = []
for (let row = 0; row < ROWS; row++) {
  let line = ''
  for (let col = 0; col < COLUMNS; col++) {
    const top = coverage(col, row * 2) >= 0.4
    const bottom = coverage(col, row * 2 + 1) >= 0.4
    line += top && bottom ? '█' : top ? '▀' : bottom ? '▄' : ' '
  }
  rows.push(line)
}

const [r, g, b] = BRAND_RGB
const header = `\
/**
 * Generated by tools/logo-cells.mjs — do not edit by hand.
 * Source: the harness web app's whale favicon, rasterized to ${COLUMNS}x${ROWS * 2}
 * pixels and packed into half-block rows drawn in DeepSeek brand blue.
 * @module dsh-tui/logo-cells
 */

/** The whale's brand color, as an RGB triple. */
export const LOGO_RGB = [${r}, ${g}, ${b}] as const

/** Half-block rows: space / ▀ / ▄ / █ per cell. */
export const LOGO_ROWS = [
${rows.map(row => `  '${row}'`).join(',\n')},
] as const
`
writeFileSync(new URL('../src/logo-cells.ts', import.meta.url), header)
console.log(`wrote src/logo-cells.ts (${COLUMNS}x${ROWS * 2} px, ${rows.length} rows)`)

